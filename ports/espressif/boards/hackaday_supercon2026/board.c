void board_init(void) {
    uint8_t variant = epd_detect_variant();
    board_set(MP_QSTR_ITC97_VARIANT, MP_OBJ_NEW_SMALL_INT(variant));
    if (variant == 0) {
        // An absent panel or invalid OTP must not select an unsafe booster setup.
        return;
    }

    itc97_itc97bus_obj_t *bus = &allocate_display_bus_or_raise()->itc97_bus;
    bus->base.type = &itc97_itc97bus_type;

    common_hal_itc97_itc97bus_construct(bus,
        &pin_GPIO21, // EPD_SCK
        &pin_GPIO47, // EPD_MOSI
        &pin_GPIO13, // EPD_CS1
        &pin_GPIO3,  // EPD_CS2
        &pin_GPIO10, // EPD_DC
        &pin_GPIO11, // EPD_RST
        &pin_GPIO48, // EPD_PWR_ENABLE, active low
        4000000, 0, 0);

    epaperdisplay_epaperdisplay_obj_t *display = &allocate_display_or_raise()->epaper_display;
    display->base.type = &epaperdisplay_epaperdisplay_type;

    epaperdisplay_construct_args_t args = EPAPERDISPLAY_CONSTRUCT_ARGS_DEFAULTS;
    args.bus = bus;
    if (variant == 1) {
        args.start_sequence = display_start_sequence_b1;
        args.start_sequence_len = sizeof(display_start_sequence_b1);
        args.refresh_sequence = display_refresh_sequence_b1;
        args.refresh_sequence_len = sizeof(display_refresh_sequence_b1);
    } else {
        args.start_sequence = display_start_sequence_084;
        args.start_sequence_len = sizeof(display_start_sequence_084);
        args.refresh_sequence = display_refresh_sequence_084;
        args.refresh_sequence_len = sizeof(display_refresh_sequence_084);
    }
    args.stop_sequence = display_stop_sequence;
    args.stop_sequence_len = sizeof(display_stop_sequence);
    // ITC97Bus waits for ready only after the complete booster ramp, not
    // between its individual writes (which would prevent it becoming ready).
    args.refresh_sequence_wait_for_busy = false;
    args.width = 960;
    args.height = 672;
    args.ram_width = 960;
    args.ram_height = 672;
    args.write_black_ram_command = 0x10;
    args.write_color_ram_command = 0x11;
    args.highlight_color = 0xFF0000;
    args.black_bits_inverted = true;
    args.color_bits_inverted = false;
    args.busy_pin = &pin_GPIO12;
    args.busy_pin2 = &pin_GPIO8;
    args.busy_state = false;
    // Allow explicit refreshes at any time while bringing up the panel.
    args.seconds_per_frame = 0.0;
    common_hal_epaperdisplay_epaperdisplay_construct(display, &args);
    // EPaperDisplay defaults to MSB-first pixels (084). B1 expects the pixels
    // within each byte in the opposite order, matching epd.py's reverse_byte().
    // Change framebuffer packing, not SPI bit order: commands stay MSB-first.
    display->core.colorspace.reverse_pixels_in_byte = variant != 1;
    // iTC97 encodes white=(0,0), black=(1,0), red=(0,1). Never set both
    // RAM-plane bits for a red pixel: that selects an unused waveform table.
    display->core.colorspace.tricolor_highlight_is_white = true;
    board_set(MP_QSTR_DISPLAY, MP_OBJ_FROM_PTR(display));
}

void board_deinit(void) {
    common_hal_displayio_release_displays();
}

