// OTP is read over the bidirectional SDA pin before ITC97Bus takes ownership of
// the pins and routes them to hardware SPI. GPIO45 is not connected to the panel.
#define EPD_SCK GPIO_NUM_21
#define EPD_SDA GPIO_NUM_47
#define EPD_CS1 GPIO_NUM_13
#define EPD_CS2 GPIO_NUM_3
#define EPD_DC GPIO_NUM_10
#define EPD_RST GPIO_NUM_11
#define EPD_PWR GPIO_NUM_48
#define EPD_OTP_SIZE (88)

static void epd_otp_write_byte(uint8_t value) {
    for (uint8_t mask = 0x80; mask != 0; mask >>= 1) {
        gpio_set_level(EPD_SDA, (value & mask) != 0);
        mp_hal_delay_us(10);
        gpio_set_level(EPD_SCK, true);
        mp_hal_delay_us(10);
        gpio_set_level(EPD_SCK, false);
    }
}

static uint8_t epd_otp_read_byte(void) {
    uint8_t value = 0;
    for (uint8_t bit = 0; bit < 8; bit++) {
        mp_hal_delay_us(10);
        gpio_set_level(EPD_SCK, true);
        mp_hal_delay_us(10);
        value = (value << 1) | gpio_get_level(EPD_SDA);
        gpio_set_level(EPD_SCK, false);
    }
    return value;
}

static void epd_otp_command(uint8_t command, const uint8_t *data, size_t length) {
    gpio_set_level(EPD_DC, false);
    gpio_set_level(EPD_CS1, false);
    gpio_set_level(EPD_CS2, false);
    epd_otp_write_byte(command);
    gpio_set_level(EPD_CS1, true);
    gpio_set_level(EPD_CS2, true);
    gpio_set_level(EPD_DC, true);
    gpio_set_level(EPD_CS1, false);
    gpio_set_level(EPD_CS2, false);
    for (size_t i = 0; i < length; i++) {
        epd_otp_write_byte(data[i]);
    }
    gpio_set_level(EPD_CS1, true);
    gpio_set_level(EPD_CS2, true);
}

static void epd_otp_read(uint8_t command, uint8_t *otp) {
    // Only the master COG may drive SDA during readback.
    gpio_set_level(EPD_DC, false);
    gpio_set_level(EPD_CS1, false);
    epd_otp_write_byte(command);
    gpio_set_level(EPD_DC, true);
    gpio_set_level(EPD_SDA, true);
    gpio_set_direction(EPD_SDA, GPIO_MODE_INPUT);
    (void)epd_otp_read_byte(); // Dummy byte before the fuse data.
    for (size_t i = 0; i < EPD_OTP_SIZE; i++) {
        otp[i] = epd_otp_read_byte();
    }
    gpio_set_level(EPD_CS1, true);
    gpio_set_level(EPD_SDA, false);
    gpio_set_direction(EPD_SDA, GPIO_MODE_OUTPUT);
}

static void epd_otp_reset(void) {
    // Active-low power enable. Observe the minimum rail-discharge interval
    // between probe attempts, as well as before the first attempt.
    gpio_set_level(EPD_PWR, true);
    gpio_set_level(EPD_RST, true);
    mp_hal_delay_ms(1500);
    gpio_set_level(EPD_PWR, false);
    mp_hal_delay_ms(800);
    mp_hal_delay_ms(50);
    gpio_set_level(EPD_RST, false);
    mp_hal_delay_ms(100);
    gpio_set_level(EPD_RST, true);
    mp_hal_delay_ms(400);
}

static uint8_t epd_detect_variant(void) {
    // No pin objects or heap allocations are needed during early board init.
    gpio_set_level(EPD_PWR, true);
    gpio_set_level(EPD_RST, true);
    gpio_set_level(EPD_CS1, true);
    gpio_set_level(EPD_CS2, true);
    gpio_set_level(EPD_DC, false);
    gpio_set_level(EPD_SCK, false);
    gpio_set_level(EPD_SDA, false);
    const gpio_config_t config = {
        .pin_bit_mask = (1ULL << EPD_PWR) | (1ULL << EPD_RST) |
            (1ULL << EPD_CS1) | (1ULL << EPD_CS2) | (1ULL << EPD_DC) |
            (1ULL << EPD_SCK) | (1ULL << EPD_SDA),
        .mode = GPIO_MODE_OUTPUT,
        .pull_up_en = GPIO_PULLUP_DISABLE,
        .pull_down_en = GPIO_PULLDOWN_DISABLE,
        .intr_type = GPIO_INTR_DISABLE,
    };
    gpio_config(&config);

    uint8_t otp[EPD_OTP_SIZE];
    uint8_t variant = 0;
    epd_otp_reset();
    epd_otp_command(0xA1, (const uint8_t[]) {0x00}, 1);
    epd_otp_command(0xA7, (const uint8_t[]) {0x80}, 1);
    epd_otp_command(0xA3, (const uint8_t[]) {0x00, 0x40}, 2);
    epd_otp_read(0xA8, otp);
    if (otp[0x00] == 0xA5 && otp[0x17] == 0x3B && otp[0x0D] == 0x3B) {
        variant = 84;
    } else {
        epd_otp_reset();
        epd_otp_command(0x70, (const uint8_t[]) {0x71, 0x36}, 2);
        epd_otp_read(0xB9, otp);
        // B1 has a different layout; do not identify it by a header byte.
        if (otp[0x16] == 0x3B && otp[0x0D] == 0x3B && (otp[0x28] & 0x80) != 0) {
            variant = 1;
        }
    }

    // Neither probe enables the booster. Power off without releasing the bus
    // pins; the ITC97Bus constructor will take them over after a successful read.
    gpio_set_level(EPD_DC, false);
    gpio_set_level(EPD_RST, false);
    gpio_set_level(EPD_PWR, true);
    return variant;
}

